def edit(path, old, new, count=1):
    if not _section_on:
        return
    text = path.read_text()
    if new in text:
        print(f"already  {path}")
        return
    if text.count(old) != count:
        if os.environ.get("PATCH_KEEP_GOING"):
            print(f"MISMATCH {path.name}: {old[:150]!r}")
            return
        sys.exit(f"fw_speed_fixes: expected {count} of {old!r} in {path}, found {text.count(old)}")
    path.write_text(text.replace(old, new))
    print(f"patched  {path}")


