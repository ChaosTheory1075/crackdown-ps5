#!/usr/bin/env python3
"""Make Crackdown 3's install data from the working cd3 prefix (run in WSL, on our build PC only).

    make_cd3_template.py PREFIX HARVEST OUT

PREFIX   the prefix that plays on the console (/root/cd3/ps5lib/prefixes/cd3)
HARVEST  the Windows 11 harvest it was built from (/root/cd3/wine-uwp-data/windows: Windows/..., Program Files/...)
OUT      Downloads/Crackdown/Extras/Crackdown 3/install-data

Writes:
  OUT/template/            the prefix without any of Microsoft's files and without the player's data
                           (Wine's own files, DXVK, vkd3d-proton, the registry, the generated registrations)
  OUT/ms-files.tsv         every Microsoft file the prefix needs: prefix path <TAB> harvest path <TAB> size <TAB> sha256
                           (the PC helper rebuilds them from the player's own Windows 11 ISO and checks each hash)
  OUT/template-files.tsv   what the template holds (path, size, sha256), for the console installer's checks
A Microsoft file is one that is byte-identical to a file of the harvest, or any file under drive_c/wineuwp.
"""
import hashlib
import os
import shutil
import sys

prefix, harvest, out = (os.path.abspath(a) for a in sys.argv[1:4])


def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        while chunk := f.read(1 << 22):
            h.update(chunk)
    return h.hexdigest()


# the harvest by content
by_hash = {}
for dp, dn, fn in os.walk(harvest):
    for f in fn:
        p = os.path.join(dp, f)
        rel = os.path.relpath(p, harvest).replace(os.sep, "/")
        if not (rel.startswith("Windows/") or rel.startswith("Program Files/")):
            continue  # the generated .reg files and harvest-missing.txt are Wine-made, not Microsoft's
        by_hash.setdefault(sha(p), rel)

# the player's own data never goes into the template
PLAYER = ("drive_c/users/root/appdata/local/wineuwp/", "drive_c/users/prospero/appdata/local/wineuwp/",
          "drive_c/users/root/appdata/local/packages/", "drive_c/users/prospero/appdata/local/packages/",
          "drive_c/users/public/wineuwp-launched.uri", "drive_c/probe-xboxauth.exe")

tmpl = os.path.join(out, "template")
if os.path.exists(tmpl):
    shutil.rmtree(tmpl)
os.makedirs(tmpl)
ms_rows, tmpl_rows, skipped = [], [], []
for dp, dn, fn in os.walk(prefix):
    reldir = os.path.relpath(dp, prefix)
    for d in dn:
        # keep every folder (empty ones too: the user tree, Desktop, ...) except the player's data folders
        rel = os.path.normpath(os.path.join(reldir, d)).replace(os.sep, "/")
        if not any((rel.lower() + "/").startswith(x) for x in PLAYER if x.endswith("/")):
            os.makedirs(os.path.join(tmpl, rel), exist_ok=True)
    for f in fn:
        p = os.path.join(dp, f)
        if os.path.islink(p):
            skipped.append((os.path.relpath(p, prefix), "symlink"))
            continue
        rel = os.path.normpath(os.path.join(reldir, f)).replace(os.sep, "/")
        low = rel.lower()
        if any(low.startswith(x) for x in PLAYER):
            skipped.append((rel, "player data"))
            continue
        size = os.path.getsize(p)
        h = sha(p)
        if h in by_hash and size > 0:
            ms_rows.append((rel, by_hash[h], size, h))
            continue
        if low.startswith("drive_c/wineuwp/"):
            if low.endswith(".reg") or low.endswith("harvest-missing.txt"):
                pass  # generated by Wine's wineuwp-setup: ours to ship
            else:
                skipped.append((rel, "MICROSOFT FILE NOT IN THE HARVEST"))
                continue
        dst = os.path.join(tmpl, rel)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.copy2(p, dst)
        tmpl_rows.append((rel, size, h))

with open(os.path.join(out, "ms-files.tsv"), "w") as f:
    for r in sorted(ms_rows):
        f.write("\t".join(map(str, r)) + "\n")
with open(os.path.join(out, "template-files.tsv"), "w") as f:
    for r in sorted(tmpl_rows):
        f.write("\t".join(map(str, r)) + "\n")
print(f"template: {len(tmpl_rows)} files, {sum(r[1] for r in tmpl_rows) / 1e6:.1f} MB")
print(f"microsoft (rebuilt by the PC helper): {len(ms_rows)} files, {sum(r[2] for r in ms_rows) / 1e6:.1f} MB")
for rel, why in skipped:
    print(f"left out: {rel} ({why})")
